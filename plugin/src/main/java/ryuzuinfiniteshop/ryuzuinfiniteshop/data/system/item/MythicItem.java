package ryuzuinfiniteshop.ryuzuinfiniteshop.data.system.item;

import lombok.Value;
import org.bukkit.ChatColor;
import org.bukkit.Material;
import org.bukkit.configuration.serialization.ConfigurationSerializable;
import org.bukkit.inventory.ItemStack;
import ryuzuinfiniteshop.ryuzuinfiniteshop.config.Config;
import ryuzuinfiniteshop.ryuzuinfiniteshop.config.LanguageKey;
import ryuzuinfiniteshop.ryuzuinfiniteshop.util.configuration.CurrentMythicItemMatcher;
import ryuzuinfiniteshop.ryuzuinfiniteshop.util.configuration.LegacyMythicItemMatcher;
import ryuzuinfiniteshop.ryuzuinfiniteshop.util.configuration.MythicInstanceProvider;
import ryuzuinfiniteshop.ryuzuinfiniteshop.util.inventory.ItemUtil;
import ryuzuinfiniteshop.ryuzuinfiniteshop.util.inventory.NBTUtil;

import java.util.LinkedHashMap;
import java.util.Map;

@Value
public class MythicItem implements ConfigurationSerializable {
    String id;
    int amount;

    /**
     * Items generated by MythicMobs per ID. Shops show and hand out the same items over and over (every GUI refresh,
     * every trade, NPC equipment every few seconds), so each is generated once and copied; cleared on reloads of
     * SIS and MythicMobs ({@link #clearCache()}).
     */
    private static final Map<String, ItemStack> GENERATED = new java.util.concurrent.ConcurrentHashMap<>();

    public static void clearCache() {
        GENERATED.clear();
    }

    public ItemStack convertItemStack() {
        if (!MythicInstanceProvider.isLoaded())
            return ItemUtil.clone(NBTUtil.setNMSTag(ItemUtil.getNamedItem(Material.REDSTONE_BLOCK, ChatColor.RED + LanguageKey.ERROR_INVALID_LOADED_MYTHICMOBS.getMessage(id)), "Error", id), amount);
        ItemStack template = GENERATED.get(id);
        if (template == null) {
            template = MythicInstanceProvider.getInstance().getMythicItem(id, 1);
            if (template == null)
                return ItemUtil.clone(NBTUtil.setNMSTag(ItemUtil.getNamedItem(Material.REDSTONE_BLOCK, ChatColor.RED + LanguageKey.ERROR_MYTHICMOBS_INVALID_ID.getMessage(id)), "Error", id), amount);
            GENERATED.put(id, template);
        }
        ItemStack item = template.clone();
        item.setAmount(amount);
        return item;
    }

    /** Whether this item cannot be generated (MythicMobs missing, or no item with this ID). */
    public boolean isError() {
        if (!MythicInstanceProvider.isLoaded()) return true;
        return GENERATED.containsKey(id) ? false : NBTUtil.getNMSStringTag(convertItemStack(), "Error") != null;
    }

    /**
     * Decides how a stack put into (or loaded into) a shop is kept. A MythicMobs item is always replaced by a
     * {@link MythicItem} (MMID + amount), so the shop hands out exactly what the current MythicMobs generates.
     * The MMID is taken from, in order:
     * <ol>
     *     <li>the item itself ({@code mythicmobs:type}, or a 1.15.2 {@code MYTHIC_TYPE} left in custom data);</li>
     *     <li>the 1.15.2 item definitions in {@code legacy-mythic-items/} ({@link LegacyMythicItemMatcher});</li>
     *     <li>the items of the running MythicMobs ({@link CurrentMythicItemMatcher}).</li>
     * </ol>
     * Not replaced: IDs the current MythicMobs does not have, IDs listed in {@code MythicItemExcludedIDs}, and items
     * whose lore text differs from the item the current MythicMobs generates (e.g. Lv2 or per-item stats kept in the
     * lore), since saving them by MMID would lose that lore.
     *
     * @return a {@link MythicItem} replacing {@code item}, or null to keep {@code item} as it is
     */
    static Object resolve(ItemStack item) {
        String error = NBTUtil.getNMSStringTag(item, "Error");
        if (error != null) return new MythicItem(error, item.getAmount());
        if (!MythicInstanceProvider.isLoaded()) return null;
        String id = MythicInstanceProvider.getInstance().getID(item);
        if (id == null) id = LegacyMythicItemMatcher.findId(item);
        if (id == null) id = CurrentMythicItemMatcher.findId(item);
        if (id == null || id.isBlank() || Config.isMythicItemExcluded(id)) return null;
        // Also false when the current MythicMobs has no item with this ID.
        if (!CurrentMythicItemMatcher.hasSameLoreAsCurrent(item, id)) return null;
        return new MythicItem(id, item.getAmount());
    }

    /** Explains, step by step, how {@link #resolve(ItemStack)} treats this item (for {@code /sis mmid}). */
    public static java.util.List<String> explain(ItemStack item) {
        java.util.List<String> result = new java.util.ArrayList<>();
        if (ItemUtil.isAir(item)) {
            result.add("no item in hand");
            return result;
        }
        if (!MythicInstanceProvider.isLoaded()) {
            result.add("MythicMobs is not loaded");
            return result;
        }
        String tagId = MythicInstanceProvider.getInstance().getID(item);
        result.add("1. MMID on the item: " + (tagId == null ? "none" : tagId));
        String legacyId = tagId != null ? null : LegacyMythicItemMatcher.findId(item);
        if (tagId == null) result.add("2. legacy definitions: " + (legacyId == null ? "no match" : legacyId));
        String currentId = null;
        if (tagId == null && legacyId == null) {
            currentId = CurrentMythicItemMatcher.findId(item);
            for (String line : CurrentMythicItemMatcher.explain(item)) result.add("3. current MythicMobs: " + line);
        }
        String id = tagId != null ? tagId : legacyId != null ? legacyId : currentId;
        if (id == null) {
            result.add("=> kept as an item (no MMID found)");
            return result;
        }
        if (Config.isMythicItemExcluded(id)) {
            result.add("=> kept as an item (" + id + " is in MythicItemExcludedIDs)");
            return result;
        }
        java.util.Optional<java.util.List<String>> lore = CurrentMythicItemMatcher.currentPlainLore(id);
        if (lore == null || lore.isEmpty()) {
            result.add("=> kept as an item (MythicMobs has no item " + id + ")");
            return result;
        }
        java.util.List<String> itemLore = CurrentMythicItemMatcher.plainLore(item);
        if (!lore.get().equals(itemLore)) {
            result.add("=> kept as an item (lore differs from " + id + ")");
            result.add("   MythicMobs: " + lore.get());
            result.add("   item:       " + itemLore);
            return result;
        }
        result.add("=> saved as MMID " + id);
        return result;
    }

    @Override
    public Map<String, Object> serialize() {
        Map<String, Object> result = new LinkedHashMap<>();
        result.put("id", id);
        result.put("amount", amount);
        return result;
    }

    public static MythicItem deserialize(Map<String, Object> map) {
        return new MythicItem(map.get("id").toString(), Integer.parseInt(map.get("amount").toString()));
    }
}
